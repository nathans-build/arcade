// opens focused on it (?topic=<id>). Its `topics` should list every topic it can focus on.
// `styles: ["action"]` (required, 1 or 2 ids from window.STYLES below; the first is its main style)
// drives the play-style chips and the menu's rows. A game with two styles shows in both rows.
// `length: "quick" | "adventure"` (required): "adventure" means it saves progress or plays in
// longer sessions (stories, journeys, levels); "quick" is a pick-up-and-play round.
// `inspiredBy: "Pac-Man"` (optional) is the classic it plays like. It's only used by the menu's
// search (typing "pac" finds Maze Muncher); it isn't shown on the cabinet.
