/** Challenges for one grade, with `{g}` in the standard filled in. */
export function mapChallengesFor(grade: Grade): MapChallenge[] {
  return MAP_CHALLENGES.filter((c) => c.grades.includes(grade)).map((c) => ({ ...c, standard: resolveStandard(c.standard, grade) }));
}

export function resolveStandard(std: string | Partial<Record<Grade, string>>, grade: Grade): string {
  if (typeof std === "string") return std.replace("{g}", grade);
  return std[grade] ?? "";
}
