/*
 * Map challenges for the jungle crossroads, by grade band.
 *
 * "dir" challenges are answered by an exit direction (N/E/S/W on the compass rose).
 * "sign" challenges put a label on each exit's sign; the first sign listed is correct and
 * the signs are dealt to the exits at random.
 *
 * `standard` is one code per grade (or a string where {g} becomes the grade).
 * scripts/check-data.ts checks every "dir" answer against a truth table and, where the
 * test knows real coordinates for the two places, against the actual compass bearing.
 */
