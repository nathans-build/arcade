export interface Face {
  /** Left x of each eye, and the eye row. */
  ex: number[];
  ey: number;
  /** Eye size in pixels (default 1x1). */
  ew?: number;
  eh?: number;
  /** Colour key for the eye (default K). */
  eye?: string;
  /** Skin key under the face (used for blinks and to clear the mouth). */
  skin: string;
  /** Mouth: left x (2 px wide) and row; omit for beaks, visors and hoods. */
  mx?: number;
  my?: number;
  /** Mouth colour key (default z, a dark brown). */
  mc?: string;
  /** Eyelid colour key for blinks (default: the skin). */
  lid?: string;
  /** Big cartoon eyes: happy shows ^ ^ eyes. */
  big?: boolean;
  /** Colour key for eyebrows (default K); robots with dark screens use their glow colour. */
  brow?: string;
}

export interface SpriteDef {
  rows: string[];
  /** Optional second frame (wings, tails, sheet hem). */
  alt?: string[];
  colors?: Record<string, string>;
  face?: Face;
  /** Pixels above the floor (flying/floating characters). */
  lift?: number;
  float?: boolean;
  /** Emote bubbles always shown (no readable face). */
  noFace?: boolean;
  /** Draw at this whole-number multiple of the normal pixel size (big animals: the sharks). */
  scale?: number;
}

