export const CELL_ROWS = 9;

function glyph(ch: string): Glyph {
  return G[ch] ?? G[ch.toUpperCase()] ?? G["?"];
}

function glyphWidth(ch: string): number {
  return Math.max(...glyph(ch).rows.map((r) => r.length));
}

/** Pixel width of `s` at `scale` (1px gap between glyphs). */
export function textWidth(s: string, scale = 1): number {
  if (!s) return 0;
  let w = 0;
  for (const ch of s) w += glyphWidth(ch) + 1;
  return (w - 1) * scale;
}

/** First and last cell rows that `s` lights up (for vertical centring). */
export function rowSpan(s: string): [number, number] {
  let lo = CELL_ROWS;
  let hi = 0;
  for (const ch of s) {
    const gl = glyph(ch);
    gl.rows.forEach((row, i) => {
      if (row.includes("#")) {
        lo = Math.min(lo, gl.top + i);
        hi = Math.max(hi, gl.top + i);
      }
    });
  }
  return lo > hi ? [2, 6] : [lo, hi];
}

/** Calls `plot(x, y)` for every lit pixel of `s` (unscaled): left edge at 0, cell top at 0. */
export function forEachPixel(s: string, plot: (x: number, y: number) => void) {
  let cx = 0;
  for (const ch of s) {
    const gl = glyph(ch);
    gl.rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") plot(cx + x, gl.top + y);
    });
    cx += glyphWidth(ch) + 1;
  }
}

/** True when every character of `s` has a real glyph. */
export function hasGlyphs(s: string): boolean {
  for (const ch of s) if (!(ch in G) && !(ch.toUpperCase() in G)) return false;
  return true;
}
