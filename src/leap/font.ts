/*
 * Lane Leap's bitmap pixel font, drawn straight onto the 320x200 canvas so log labels and
 * home answers stay crisp at any zoom and never wait on a web font.
 *
 * Every glyph sits on a 9-row cell: capitals and digits use rows 2-6 (3x5 mostly),
 * lowercase has its x-height on rows 3-6 with ascenders on row 2 and descenders on row 7,
 * superscripts use rows 0-3 and subscripts rows 5-8. Pure data + metrics (no DOM), so the
 * content checker can measure labels too.
 */

interface Glyph {
  top: number;
  rows: string[];
}

