/*
 * Maze Muncher's original maze layouts. Each maze is drawn as its LEFT half plus the centre
 * column; the right half is the mirror image, so every maze is symmetric.
 *
 *   #  wall            .  data dot           o  power pellet slot (the A–D answer pellets)
 *   =  pen door        p  pen (critter home) (space) open floor with no dot (tunnel)
 *   H  hero start      F  bonus item spot
 *
 * A row whose two edge cells are open is a wrap-around tunnel. Big mazes (grades 3–12) are
 * 25×24 tiles; small mazes (K–2) are 19×19 tiles, leaving wider side panels for bigger labels.
 */

export interface LayoutDef {
  name: string;
  half: string[];
}

