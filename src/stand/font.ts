export const FONT_H = 7;

function glyph(ch: string): Glyph {
  return G[ch] ?? G[ch.toUpperCase()] ?? G["?"];
}

function glyphWidth(ch: string): number {
  return glyph(ch)[1][0].length;
}

/** Pixel width of `s` at `scale` (1px gap between glyphs). */
export function textWidth(s: string, scale = 1): number {
  if (!s) return 0;
  let w = 0;
  for (const ch of s) w += glyphWidth(ch) + 1;
  return (w - 1) * scale;
}

/** Calls `plot(x, y)` for every lit pixel of `s` (unscaled): left edge 0, cell top 0 (7 rows). */
export function forEachPixel(s: string, plot: (x: number, y: number) => void) {
  let cx = 0;
  for (const ch of s) {
    const [top, rows] = glyph(ch);
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") plot(cx + x, top + y);
    });
    cx += glyphWidth(ch) + 1;
  }
}

/** True when every character of `s` has its own glyph (no fallback to "?"). */
export function hasGlyphs(s: string): boolean {
  for (const ch of s) if (!(ch in G)) return false;
  return true;
}
